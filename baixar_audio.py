# ---------- utilidades ----------
def fmt_bytes(n):
    if not n:
        return "?"
    for u in ("B", "KB", "MB", "GB"):
        if n < 1024:
            return f"{n:.1f} {u}"
        n /= 1024
    return f"{n:.1f} TB"


def fmt_eta(s):
    if s is None:
        return "?"
    s = int(s)
    return f"{s // 60:02d}:{s % 60:02d}"


def _dir_ok(d):
    """A pasta serve se tiver ffmpeg e ffprobe com tamanho maior que zero."""
    ext = ".exe" if os.name == "nt" else ""
    for nome in ("ffmpeg", "ffprobe"):
        p = os.path.join(d, nome + ext)
        if not (os.path.isfile(p) and os.path.getsize(p) > 0):
            return False
    return True


def achar_ffmpeg():
    """Retorna a pasta com ffmpeg + ffprobe funcionando (ou None)."""
    exe = shutil.which("ffmpeg")
    if exe and _dir_ok(os.path.dirname(exe)):
        return os.path.dirname(exe)
    local = os.environ.get("LOCALAPPDATA", "")
    prog = os.environ.get("ProgramFiles", r"C:\Program Files")
    cands = glob.glob(os.path.join(local, "Microsoft", "WinGet", "Packages", "**", "ffmpeg.exe"), recursive=True)
    cands += [r"C:\ffmpeg\bin\ffmpeg.exe"]
    cands += glob.glob(os.path.join(prog, "ffmpeg*", "**", "ffmpeg.exe"), recursive=True)
    cands.sort(key=lambda p: os.path.getmtime(p) if os.path.exists(p) else 0, reverse=True)
    for c in cands:
        if os.path.isfile(c) and _dir_ok(os.path.dirname(c)):
            return os.path.dirname(c)
    return None


